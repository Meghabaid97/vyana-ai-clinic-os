export function getLanguage(): Language {
  return (localStorage.getItem("vyana-lang") as Language) || "en";
}

export function setLanguage(lang: Language) {
  localStorage.setItem("vyana-lang", lang);
  window.dispatchEvent(new CustomEvent("vyana-lang-change", { detail: lang }));
}

export function t(key: string, params?: Record<string, string | number>): string {
  const lang = getLanguage();
  let text = translations[lang]?.[key] || translations.en[key] || key;
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replace(`{${k}}`, String(v));
    });
  }
  return text;
}

export function useLanguage() {
  const [lang, setLang] = useState<Language>(getLanguage());

  useEffect(() => {
    const handler = (e: Event) => {
      setLang((e as CustomEvent).detail);
    };
    window.addEventListener("vyana-lang-change", handler);
    return () => window.removeEventListener("vyana-lang-change", handler);
  }, []);

  const changeLanguage = useCallback((newLang: Language) => {
    setLanguage(newLang);
    setLang(newLang);
  }, []);

  return { lang, changeLanguage, t };
}
